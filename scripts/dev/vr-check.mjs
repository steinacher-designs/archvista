// VR check with Meta's WebXR emulator (iwer): button appears, session starts, stick walks, snap turn, exit restores.
import { chromium } from "playwright"; import http from "node:http"; import { readFile } from "node:fs/promises"; import path from "node:path";
const [dir, iwerPath] = process.argv.slice(2);
const types = { ".html": "text/html", ".js": "text/javascript", ".json": "application/json", ".svg": "image/svg+xml" };
const srv = http.createServer(async (q, r) => { try { let f = decodeURIComponent(q.url.split("?")[0]); if (f.endsWith("/")) f += "index.html"; const buf = await readFile(path.join(dir, f)); r.writeHead(200, { "content-type": types[path.extname(f)] ?? "application/octet-stream" }); r.end(buf); } catch { r.writeHead(404); r.end(); } }).listen(0);
const b = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
const iwer = await readFile(iwerPath, "utf8");
await p.addInitScript(iwer + ";window.__xr=new IWER.XRDevice(IWER.metaQuest3);window.__xr.installRuntime({ forceInstall: true });");
const out = [];
const ok = (n, c, extra = "") => out.push(`${c ? "✓" : "✗"} ${n}${extra ? " " + extra : ""}`);
await p.goto(`http://localhost:${srv.address().port}/`);
await p.waitForFunction(() => window.archvista && !document.querySelector(".av-loading"), null, { timeout: 180000 });
await p.waitForTimeout(1500);
ok("VR-Brille button visible", await p.locator("[data-a=vr]").isVisible());
await p.locator("[data-a=vr]").click();
await p.waitForFunction(() => window.archvista.inVR && window.archvista.renderer.xr.isPresenting, null, { timeout: 20000 }).catch(() => {});
ok("VR session running", await p.evaluate(() => window.archvista.renderer.xr.isPresenting));
const rig = () => p.evaluate(() => { const r = window.archvista.scene.getObjectByName("vr-rig"); return r ? { x: r.position.x, y: r.position.y, z: r.position.z, ry: r.rotation.y } : null; });
const f0 = await p.evaluate(() => window.archvista.renderer.info.render.frame);
const a = await rig();
ok("standing on the floor at the entrance", a && Number.isFinite(a.y), JSON.stringify(a));
await p.evaluate(() => window.__xr.controllers.left.updateAxes("thumbstick", 0, -1));
await p.waitForTimeout(2500);
await p.evaluate(() => window.__xr.controllers.left.updateAxes("thumbstick", 0, 0));
const b2 = await rig();
const moved = Math.hypot(b2.x - a.x, b2.z - a.z);
ok("left stick walks", moved > 0.3, `${moved.toFixed(2)} m`);
ok("frames rendered in VR", (await p.evaluate(() => window.archvista.renderer.info.render.frame)) > f0);
await p.evaluate(() => window.__xr.controllers.right.updateAxes("thumbstick", 1, 0));
await p.waitForTimeout(400);
await p.evaluate(() => window.__xr.controllers.right.updateAxes("thumbstick", 0, 0));
await p.waitForTimeout(300);
const c = await rig();
ok("right stick snap-turns 30°", Math.abs(Math.abs(c.ry - b2.ry) - Math.PI / 6) < 0.01, `${((c.ry - b2.ry) * 180 / Math.PI).toFixed(0)}°`);
await p.evaluate(() => window.archvista.exitVR());
await p.waitForTimeout(1000);
ok("leaving VR restores the page view", await p.evaluate(() => !window.archvista.inVR && !window.archvista.renderer.xr.enabled && document.querySelector(".av-hud").style.display === ""));
const f1 = await p.evaluate(() => window.archvista.renderer.info.render.frame);
await p.mouse.move(640, 400); await p.mouse.down(); await p.mouse.move(700, 420, { steps: 5 }); await p.mouse.up(); await p.waitForTimeout(600);
ok("normal 3D works again afterwards", (await p.evaluate(() => window.archvista.renderer.info.render.frame)) > f1);
out.push("page errors: " + (errs.length ? errs.join(" | ") : "none"));
console.log(out.join("\n")); await b.close(); srv.close();

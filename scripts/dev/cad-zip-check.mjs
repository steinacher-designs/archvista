// End-to-end: drop a ZIP (DXF with CAD materials + texture image) into the app — materials arrive, own texture is used.
import { chromium } from "playwright"; import http from "node:http"; import { readFile } from "node:fs/promises"; import path from "node:path";
const [dist, zip, out] = process.argv.slice(2);
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json", ".svg": "image/svg+xml" };
const srv = http.createServer(async (q, r) => { let f = decodeURIComponent(q.url.split("?")[0]); if (f === "/") f = "/index.html"; try { const b = await readFile(path.join(dist, f)); r.writeHead(200, { "content-type": types[path.extname(f)] ?? "application/octet-stream" }); r.end(b); } catch { r.writeHead(404); r.end(); } }).listen(0);
const b = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.addInitScript(() => { localStorage.setItem("av-maxfps", "1"); localStorage.setItem("av-auto", "0"); sessionStorage.setItem("av-gpu-hint", "off"); });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
const res = []; const ok = (n, c, x = "") => res.push(`${c ? "✓" : "✗"} ${n}${x ? " " + x : ""}`);
await p.goto(`http://localhost:${srv.address().port}/`);
await p.locator("details.guide summary").click();
ok("guide opens", await p.locator("details.guide[open] li").count() === 4);
await p.screenshot({ path: `${out}/guide.png` });
await p.getByTestId("file").setInputFiles(zip);
await p.getByTestId("viewer").waitFor({ timeout: 120000 });
await p.waitForTimeout(10000);
const meshes = await p.evaluate(() => { const ids = new Set(); window.__archvistaViewer.scene.traverse((o) => { if (o.isMesh && o.userData.key) ids.add(o.userData.presetId); }); return [...ids]; });
ok("own texture material in 3D", meshes.some((id) => id.startsWith("img:")), meshes.join(", "));
ok("roof tiles from CAD name", meshes.includes("roof_clay"));
ok("floor tiles from CAD name", meshes.includes("white_tiles"));
const hasMap = await p.evaluate(() => { let m = null; window.__archvistaViewer.scene.traverse((o) => { if (o.isMesh && String(o.userData.presetId).startsWith("img:")) m = o.material; }); return !!m?.map?.image; });
ok("texture image loaded", hasMap);
await p.getByTestId("tab-materials").click();
await p.waitForTimeout(800);
const first = await p.locator(".mhead small").allTextContents();
ok("CAD names shown in the list", first.some((t) => t.includes("Holz Lärche Fassade")), first.slice(0, 3).join(" | "));
await p.locator(".mhead", { hasText: "Holz Lärche Fassade" }).first().click();
await p.waitForTimeout(2500);
ok("group 'Aus der CAD-Datei' in picker", await p.locator(".mgl", { hasText: "Aus der CAD-Datei" }).count() === 1);
await p.screenshot({ path: `${out}/cad-materials.png`, timeout: 120000 });
res.push("page errors: " + (errs.length ? errs.join(" | ") : "none"));
console.log(res.join("\n")); await b.close(); srv.close();
